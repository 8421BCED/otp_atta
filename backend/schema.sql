-- OTP Attendance Database Schema for Francis Xavier Engineering College
CREATE DATABASE IF NOT EXISTS otp_attendance;
USE otp_attendance;

-- 1. Users Table
CREATE TABLE IF NOT EXISTS users (
    id INT AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role ENUM('student', 'staff', 'hod', 'principal') NOT NULL,
    department VARCHAR(50) DEFAULT 'IT',
    roll_number VARCHAR(50) NULL,
    year_of_study VARCHAR(10) NULL,
    phone VARCHAR(20) NULL,
    is_active TINYINT(1) DEFAULT 1,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. Device Locks (Anti-Proxy Protection)
CREATE TABLE IF NOT EXISTS device_locks (
    id INT AUTO_INCREMENT PRIMARY KEY,
    user_id INT NOT NULL UNIQUE,
    device_id VARCHAR(255) NOT NULL,
    device_fingerprint TEXT NOT NULL,
    device_name VARCHAR(150) DEFAULT 'Mobile / Browser Device',
    platform VARCHAR(100) NULL,
    user_agent TEXT NULL,
    screen_resolution VARCHAR(50) NULL,
    ip_address VARCHAR(50) NULL,
    is_locked TINYINT(1) DEFAULT 1,
    locked_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    last_verified_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- 3. Buildings Table
CREATE TABLE IF NOT EXISTS buildings (
    id INT AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    code VARCHAR(20) NOT NULL UNIQUE,
    description VARCHAR(255) NULL
);

-- 4. Floors Table
CREATE TABLE IF NOT EXISTS floors (
    id INT AUTO_INCREMENT PRIMARY KEY,
    building_id INT NOT NULL,
    floor_number INT NOT NULL,
    name VARCHAR(50) NOT NULL,
    FOREIGN KEY (building_id) REFERENCES buildings(id) ON DELETE CASCADE
);

-- 5. Rooms Table
CREATE TABLE IF NOT EXISTS rooms (
    id INT AUTO_INCREMENT PRIMARY KEY,
    building_id INT NOT NULL,
    floor_id INT NOT NULL,
    room_number VARCHAR(20) NOT NULL,
    name VARCHAR(100) NOT NULL,
    room_type VARCHAR(50) DEFAULT 'classroom',
    capacity INT DEFAULT 60,
    department VARCHAR(50) DEFAULT 'ALL',
    FOREIGN KEY (building_id) REFERENCES buildings(id) ON DELETE CASCADE,
    FOREIGN KEY (floor_id) REFERENCES floors(id) ON DELETE CASCADE,
    UNIQUE KEY uq_building_room (building_id, room_number)
);

-- 6. Periods Table (College Schedule finishing at 4:05 PM)
CREATE TABLE IF NOT EXISTS periods (
    id INT AUTO_INCREMENT PRIMARY KEY,
    period_number INT NOT NULL,
    name VARCHAR(50) NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    is_break TINYINT(1) DEFAULT 0
);

-- 7. Active OTPs (10-second rolling OTP generated by Staff in Room)
CREATE TABLE IF NOT EXISTS active_otps (
    id INT AUTO_INCREMENT PRIMARY KEY,
    room_id INT NOT NULL,
    staff_id INT NOT NULL,
    period_id INT NOT NULL,
    otp_code VARCHAR(6) NOT NULL,
    generated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP NOT NULL,
    FOREIGN KEY (room_id) REFERENCES rooms(id) ON DELETE CASCADE,
    FOREIGN KEY (staff_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (period_id) REFERENCES periods(id) ON DELETE CASCADE
);

-- 8. Attendance Records
CREATE TABLE IF NOT EXISTS attendance_records (
    id INT AUTO_INCREMENT PRIMARY KEY,
    student_id INT NOT NULL,
    period_id INT NOT NULL,
    room_id INT NOT NULL,
    staff_id INT NULL,
    date DATE NOT NULL,
    marked_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    status ENUM('present', 'absent', 'late', 'locked_out') DEFAULT 'present',
    otp_used VARCHAR(6) NULL,
    device_id VARCHAR(255) NULL,
    FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (period_id) REFERENCES periods(id) ON DELETE CASCADE,
    FOREIGN KEY (room_id) REFERENCES rooms(id) ON DELETE CASCADE,
    UNIQUE KEY uq_student_period_date (student_id, period_id, date)
);

-- 9. Student Movements (Class / Lab Movement Tracking)
CREATE TABLE IF NOT EXISTS student_movements (
    id INT AUTO_INCREMENT PRIMARY KEY,
    student_id INT NOT NULL,
    from_room_id INT NULL,
    to_room_id INT NOT NULL,
    period_id INT NOT NULL,
    date DATE NOT NULL,
    timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    duration_minutes INT DEFAULT 0,
    note VARCHAR(255) NULL,
    FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (to_room_id) REFERENCES rooms(id) ON DELETE CASCADE,
    FOREIGN KEY (period_id) REFERENCES periods(id) ON DELETE CASCADE
);

-- 10. Holidays Management (HOD & Principal with Conflict Resolution)
CREATE TABLE IF NOT EXISTS holidays (
    id INT AUTO_INCREMENT PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    holiday_date DATE NOT NULL,
    scope ENUM('college', 'department') DEFAULT 'college',
    department VARCHAR(50) DEFAULT 'ALL',
    declared_by INT NOT NULL,
    reason TEXT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (declared_by) REFERENCES users(id) ON DELETE CASCADE
);

-- 11. Day Start Status (9:00 - 9:05 AM day lockouts)
CREATE TABLE IF NOT EXISTS student_day_locks (
    id INT AUTO_INCREMENT PRIMARY KEY,
    student_id INT NOT NULL,
    date DATE NOT NULL,
    first_otp_at TIMESTAMP NULL,
    is_locked_out TINYINT(1) DEFAULT 0,
    reason VARCHAR(255) NULL,
    FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE,
    UNIQUE KEY uq_student_date (student_id, date)
);

-- 12. Student Leave & On-Duty Applications
CREATE TABLE IF NOT EXISTS leave_applications (
    id INT AUTO_INCREMENT PRIMARY KEY,
    student_id INT NOT NULL,
    type ENUM('internal', 'external') NOT NULL DEFAULT 'internal',
    event_name VARCHAR(255) NOT NULL,
    category VARCHAR(100) DEFAULT 'Symposium / Hackathon',
    venue VARCHAR(255) DEFAULT '',
    from_date DATE NOT NULL,
    to_date DATE NOT NULL,
    is_all_day TINYINT(1) DEFAULT 1,
    from_period INT DEFAULT 1,
    to_period INT DEFAULT 7,
    reason TEXT NOT NULL,
    mentor_id INT NULL,
    status ENUM('pending_mentor', 'pending_hod', 'approved', 'rejected') NOT NULL DEFAULT 'pending_mentor',
    mentor_remarks TEXT NULL,
    mentor_reviewed_at DATETIME NULL,
    hod_remarks TEXT NULL,
    hod_reviewed_at DATETIME NULL,
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE,
    INDEX idx_student (student_id),
    INDEX idx_status (status),
    INDEX idx_dates (from_date, to_date)
);

-- 13. Sports On-Duty Passes (Physical Education Department)
CREATE TABLE IF NOT EXISTS sports_od_passes (
    id INT AUTO_INCREMENT PRIMARY KEY,
    event_name VARCHAR(150) NOT NULL,
    sport_category VARCHAR(100) DEFAULT 'General Sports',
    venue VARCHAR(150) DEFAULT 'FXEC Sports Arena',
    from_date DATE NOT NULL,
    to_date DATE NOT NULL,
    is_all_day TINYINT(1) DEFAULT 1,
    from_period INT DEFAULT 1,
    to_period INT DEFAULT 7,
    reason TEXT NULL,
    created_by INT NOT NULL,
    status VARCHAR(50) DEFAULT 'active',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS sports_od_students (
    id INT AUTO_INCREMENT PRIMARY KEY,
    pass_id INT NOT NULL,
    student_id INT NOT NULL,
    notes VARCHAR(255) NULL,
    added_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (pass_id) REFERENCES sports_od_passes(id) ON DELETE CASCADE,
    FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE,
    UNIQUE KEY uq_pass_student (pass_id, student_id)
);

-- 14. Staff Movement History
CREATE TABLE IF NOT EXISTS staff_movements (
    id INT AUTO_INCREMENT PRIMARY KEY,
    staff_id INT NOT NULL,
    from_room_id INT NULL,
    to_room_id INT NOT NULL,
    period_id INT NOT NULL DEFAULT 1,
    date DATE NOT NULL,
    timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    duration_minutes INT DEFAULT 0,
    note VARCHAR(255) NULL,
    FOREIGN KEY (staff_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (to_room_id) REFERENCES rooms(id) ON DELETE CASCADE,
    INDEX idx_staff_date (staff_id, date)
);

-- 15. AI Classroom YOLO Headcount Audits
CREATE TABLE IF NOT EXISTS classroom_headcounts (
    id INT AUTO_INCREMENT PRIMARY KEY,
    room_id INT NOT NULL,
    staff_id INT NOT NULL,
    period_id INT NOT NULL,
    otp_count INT NOT NULL DEFAULT 0,
    visual_count INT NOT NULL DEFAULT 0,
    image_url VARCHAR(255) NOT NULL,
    boxes_json JSON NULL,
    match_status VARCHAR(50) DEFAULT 'verified',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP NULL,
    INDEX idx_room_period (room_id, period_id),
    INDEX idx_expires (expires_at)
);

-- 16. Firebase Cloud Messaging (FCM) Push Notification Tokens
CREATE TABLE IF NOT EXISTS fcm_tokens (
    id INT AUTO_INCREMENT PRIMARY KEY,
    user_id INT NULL,
    role VARCHAR(50) NULL,
    department VARCHAR(50) NULL,
    token TEXT NOT NULL,
    device_info VARCHAR(255) NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY unique_user_token (user_id, token(191))
);

-- 17. User Feedback & Issue Reports
CREATE TABLE IF NOT EXISTS user_feedbacks (
    id INT AUTO_INCREMENT PRIMARY KEY,
    user_id INT NULL,
    user_name VARCHAR(255) NULL,
    user_email VARCHAR(255) NULL,
    user_role VARCHAR(50) NULL,
    category VARCHAR(100) DEFAULT 'General Feedback',
    message TEXT NOT NULL,
    rating INT DEFAULT 5,
    device_info VARCHAR(255) NULL,
    status VARCHAR(50) DEFAULT 'open',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

